export type MessageKey = keyof typeof messages;
export type Translate = (key: MessageKey) => string;

export function resolveLanguage(locale: Locale, systemLanguage = navigator.language): 'zh-CN' | 'en' {
  if (locale !== 'system') return locale;
  return /^(zh-CN|zh-SG|zh-Hans)(-|$)/i.test(systemLanguage) ? 'zh-CN' : 'en';
}

export function translator(locale: Locale): Translate {
  const index = resolveLanguage(locale) === 'zh-CN' ? 0 : 1;
  return (key) => messages[key][index];
}
